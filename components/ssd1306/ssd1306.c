static void ssd1306_write_cmd(ssd1306_t *dev, uint8_t cmd) {
    uint8_t buf[2] = {0x00, cmd};
    i2c_master_transmit(dev->i2c_dev, buf, sizeof(buf), -1);
}

static void ssd1306_write_data(ssd1306_t *dev, const uint8_t *data, size_t len) {
    uint8_t buf[len + 1];
    buf[0] = 0x40;
    memcpy(&buf[1], data, len);
    i2c_master_transmit(dev->i2c_dev, buf, len + 1, -1);
}

esp_err_t ssd1306_init(i2c_master_bus_handle_t bus_handle, ssd1306_t *dev) {
    i2c_device_config_t dev_cfg = {
        .dev_addr_length = I2C_ADDR_BIT_LEN_7,
        .device_address = 0x3C,
        .scl_speed_hz = 400000,
    };
    esp_err_t ret = i2c_master_bus_add_device(bus_handle, &dev_cfg, &dev->i2c_dev);
    if (ret != ESP_OK) return ret;

    uint8_t init_cmds[] = {
        0xAE,       // Display OFF
        0xD5, 0x80, // Set Display Clock Divide Ratio
        0xA8, 0x3F, // Set Multiplex Ratio (128x64)
        0xD3, 0x00, // Set Display Offset
        0x40,       // Set Display Start Line
        0x8D, 0x14, // Enable Charge Pump
        0x20, 0x00, // Memory Addressing Mode (Horizontal)
        0xA1,       // Column Address 128 is mapped to SEG0
        0xC8,       // Remapped mode. Scan from COM[N-1] to COM0
        0xDA, 0x12, // Set COM Pins Hardware Configuration
        0x81, 0xCF, // Set Contrast Control
        0xD9, 0xF1, // Set Pre-charge Period
        0xDB, 0x40, // Set VCOMH Deselect Level
        0xA4,       // Entire Display ON
        0xA6,       // Normal Display
        0xAF        // Display ON
    };

    for (size_t i = 0; i < sizeof(init_cmds); i++) {
        ssd1306_write_cmd(dev, init_cmds[i]);
    }

    ssd1306_clear(dev);
    return ssd1306_update(dev);
}

void ssd1306_clear(ssd1306_t *dev) {
    memset(dev->buffer, 0, sizeof(dev->buffer));
}

esp_err_t ssd1306_update(ssd1306_t *dev) {
    for (uint8_t i = 0; i < 8; i++) {
        ssd1306_write_cmd(dev, 0xB0 + i);
        ssd1306_write_cmd(dev, 0x00);
        ssd1306_write_cmd(dev, 0x10);
        ssd1306_write_data(dev, &dev->buffer[128 * i], 128);
    }
    return ESP_OK;
}

void ssd1306_draw_pixel(ssd1306_t *dev, int x, int y, bool color) {
    if (x < 0 || x >= 128 || y < 0 || y >= 64) return;
    if (color) {
        dev->buffer[x + (y / 8) * 128] |= (1 << (y % 8));
    } else {
        dev->buffer[x + (y / 8) * 128] &= ~(1 << (y % 8));
    }
}

void ssd1306_draw_line(ssd1306_t *dev, int x0, int y0, int x1, int y1, bool color) {
    int dx = x1 > x0 ? x1 - x0 : x0 - x1;
    int dy = y1 > y0 ? y1 - y0 : y0 - y1;
    int sx = x0 < x1 ? 1 : -1;
    int sy = y0 < y1 ? 1 : -1;
    int err = dx - dy;

    while (1) {
        ssd1306_draw_pixel(dev, x0, y0, color);
        if (x0 == x1 && y0 == y1) break;
        int e2 = 2 * err;
        if (e2 > -dy) { err -= dy; x0 += sx; }
        if (e2 < dx) { err += dx; y0 += sy; }
    }
}

void ssd1306_draw_rect(ssd1306_t *dev, int x, int y, int w, int h, bool color) {
    ssd1306_draw_line(dev, x, y, x + w - 1, y, color);
    ssd1306_draw_line(dev, x, y + h - 1, x + w - 1, y + h - 1, color);
    ssd1306_draw_line(dev, x, y, x, y + h - 1, color);
    ssd1306_draw_line(dev, x + w - 1, y, x + w - 1, y + h - 1, color);
}

void ssd1306_draw_char(ssd1306_t *dev, int x, int y, char c, bool invert) {
    if ((uint8_t)c > 127) return;
    for (int i = 0; i < 8; i++) {
        uint8_t line = font8x8_basic[(uint8_t)c][i];
        for (int j = 0; j < 8; j++) {
            bool pixel = (line >> j) & 0x01;
            if (invert) pixel = !pixel;
            ssd1306_draw_pixel(dev, x + i, y + j, pixel);
        }
    }
}

void ssd1306_draw_string(ssd1306_t *dev, int x, int y, const char *str, bool invert) {
    (void)TAG;
    while (*str) {
        ssd1306_draw_char(dev, x, y, *str, invert);
        x += 8;
        str++;
    }
}